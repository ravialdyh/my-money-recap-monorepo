import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { here } from './lib.mjs';

/** The component stylesheets in filename order; the numeric prefix is the cascade order. */
function componentCss() {
  const dir = resolve(here, '../src/styles/components');
  const names = readdirSync(dir)
    .filter((n) => n.endsWith('.css'))
    .sort();
  return names.map((n) => readFileSync(resolve(dir, n), 'utf8')).join('\n');
}

const tokens = readFileSync(resolve(here, '../src/tokens/tokens.css'), 'utf8');
const comps = componentCss();
const fonts = `@import url('https://fonts.googleapis.com/css2?family=Fredoka:wght@500;600;700&family=Nunito:wght@600;700;800&display=swap');\n`;
const sheet = `${fonts + tokens}\n${comps}`;
const out = `// Generated by scripts/build-styles.mjs. Do not edit by hand.\nexport const MMR_CSS = ${JSON.stringify(sheet)};\n`;
writeFileSync(resolve(here, '../src/styles/css.generated.ts'), out);
mkdirSync(resolve(here, '../dist'), { recursive: true });
writeFileSync(resolve(here, '../dist/mmr.css'), sheet);
console.log('css.generated.ts + dist/mmr.css written', sheet.length, 'chars');
