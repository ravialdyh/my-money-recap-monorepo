// Regenerates src/assets/illustrations.ts from the WebP files in ../../my-money-recap/assets/illustrations/.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const here = dirname(fileURLToPath(import.meta.url));
const src = resolve(here, '../../my-money-recap/assets/illustrations');
const names = {
  cover: 'ill-cover.webp',
  lemonade: 'ill-lemonade.webp',
  vending: 'ill-vending.webp',
  squirrel: 'ill-squirrel.webp',
  envelope: 'ill-envelope.webp',
  'avatar-fox': 'ill-avatar-fox.webp',
  'avatar-otter': 'ill-avatar-otter.webp',
  'avatar-panda': 'ill-avatar-panda.webp',
  'avatar-frog': 'ill-avatar-frog.webp',
  'avatar-owl': 'ill-avatar-owl.webp',
  'avatar-rabbit': 'ill-avatar-rabbit.webp',
  hustler: 'ill-hustler.webp',
  treat: 'ill-treat.webp',
  slowburner: 'ill-slowburner.webp',
  jar: 'ill-jar.webp',
};
const lines = [
  '// Generated by scripts/build-assets.mjs from my-money-recap/assets/illustrations/ill-*.webp. Do not edit by hand.',
  '// The recap illustrations, onboarding envelope and six avatar badges as data URIs,',
  '// so previews and stories need no asset pipeline.',
  '// Transparent WebP at roughly 2x display size (avatars 204px, 3x the 68px grid).',
  '// Style block and subject prompts: my-money-recap/docs/illustration-prompts.md.',
  'export const ILLUSTRATIONS = {',
];
for (const [k, f] of Object.entries(names)) {
  const b64 = readFileSync(resolve(src, f)).toString('base64');
  const key = /^[A-Za-z_$][\w$]*$/.test(k) ? k : `'${k}'`;
  lines.push(`  ${key}: 'data:image/webp;base64,${b64}',`);
}
lines.push('} as const;', 'export type IllustrationKey = keyof typeof ILLUSTRATIONS;');
writeFileSync(resolve(here, '../src/assets/illustrations.ts'), lines.join('\n') + '\n');
console.log('src/assets/illustrations.ts written');
